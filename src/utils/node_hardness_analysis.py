def import_graph(dataset: str) -> ig.Graph:
    """
    Load the graph exactly like ``Utils.import_graph``: relabel the sorted unique
    node ids to ``0..n-1`` (so node ids match the feature CSVs and the stored
    ``target_node`` ids) and keep the original ids in the ``name`` attribute.
    """
    file_path = os.path.join(NETWORKS_DIR, f"{dataset}.txt")
    with open(file_path, "r") as f:
        edges = [tuple(map(int, line.split())) for line in f if line.strip()]
    unique_nodes = sorted({n for e in edges for n in e})
    mapping = {old: new for new, old in enumerate(unique_nodes)}
    relabeled = [(mapping[a], mapping[b]) for a, b in edges]
    graph = ig.Graph(edges=relabeled, directed=False)
    graph.vs["name"] = unique_nodes
    return graph


def _compute_partition(graph: ig.Graph, dataset: str, alg: str) -> List[List[int]]:
    """Run ``alg`` on ``graph`` and return communities as a list of node-id lists."""
    if alg == "greedy":
        clustering = graph.community_fastgreedy().as_clustering()
        return [list(c) for c in clustering]
    if alg == "walktrap":
        clustering = graph.community_walktrap().as_clustering()
        return [list(c) for c in clustering]
    if alg == "leiden":
        import leidenalg as la
        part = la.find_partition(graph, la.ModularityVertexPartition, seed=PARTITION_SEED)
        return [list(c) for c in part]
    if alg == "dgcluster":
        # Heavy path: needs torch + the pre-trained model. Imported lazily so the
        # other algorithms work without a torch install.
        import sys
        if ROOT_DIR not in sys.path:
            sys.path.insert(0, ROOT_DIR)
        from src.community_detection.extra_algs.dgcluster.dgcluster import DGCluster
        node_clustering = DGCluster(graph, DATASET_KEYS[dataset])
        return [list(c) for c in node_clustering.communities]
    raise ValueError(f"Unknown detection algorithm: {alg}")


def get_partition(dataset: str, alg: str, graph: ig.Graph) -> List[List[int]]:
    """
    Return the cached partition for ``(dataset, alg)`` or compute, cache and return it.

    Cache file: ``outputs_review/hardness/{dataset}/partitions/{alg}.json`` storing
    ``{"algorithm", "dataset", "n_nodes", "seed", "communities": [[...], ...]}``.
    """
    cache_dir = os.path.join(OUT_DIR, dataset, "partitions")
    cache_path = os.path.join(cache_dir, f"{alg}.json")
    if os.path.exists(cache_path):
        with open(cache_path, "r") as f:
            return json.load(f)["communities"]

    print(f"  [partition] generating {alg} for {dataset} ...")
    communities = _compute_partition(graph, dataset, alg)
    # Cast to native python ints (some algorithms return numpy int ids) for JSON.
    communities = [[int(v) for v in c] for c in communities]
    check_dir(cache_dir)
    # Serialize first so a serialization error never leaves a truncated cache file.
    payload = json.dumps(
        {
            "algorithm": alg,
            "dataset": dataset,
            "n_nodes": graph.vcount(),
            "seed": PARTITION_SEED if alg in ("leiden", "dgcluster") else None,
            "communities": communities,
        }
    )
    with open(cache_path, "w") as f:
        f.write(payload)
    return communities


