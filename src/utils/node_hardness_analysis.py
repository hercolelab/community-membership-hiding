"""
Target-node difficulty (hardness) analysis.

This script answers the reviewer request:

    "It would be useful to analyse performance by simple node-level characteristics,
     such as: degree; internal versus external connections; centrality; embeddedness
     in the original community; community size."

For every detection algorithm in ``DETECTION_ALGS`` we:

1.  Build (or load from cache) the community partition of the *original* graph
    produced by that algorithm.  Partitions are cached at
    ``outputs_review/hardness/{dataset}/partitions/{algorithm}.json`` so they are
    computed only once.  If the file already exists it is reused, otherwise it is
    generated by applying the algorithm to the graph and saved.
2.  Compute, for every target node, a set of node-level "difficulty" features,
    some of them relative to the node's *original* community in that partition:
        - degree                       (global)
        - betweenness/eigenvector/pagerank centrality   (global, from feature_analysis CSVs)
        - internal_degree / external_degree / internal_ratio   (internal vs external)
        - embeddedness  (within-community local clustering)     (embeddedness)
        - participation_coef                                    (extra embeddedness measure)
        - community_size                                        (community size)
3.  Join those features with the per-target-node outcome (success rate, i.e. the
    ``goal`` field, 1 = node successfully hidden) of every evasion method, pooled
    across seeds and budget factors.
4.  Produce two complementary views (per-dataset, pooled-per-algorithm across
    datasets, and fully pooled). Each view is a folder of one PDF per feature:
        A. difficulty_curves/      : success rate vs binned feature, one line per method
        B. outcome_distributions/  : feature distribution split by hidden/not-hidden

All artefacts are written under ``outputs_review/hardness/``.

Run from the repository root, e.g.::

    python -m src.utils.node_hardness_analysis
    python -m src.utils.node_hardness_analysis --datasets kar words --algs greedy leiden
"""

