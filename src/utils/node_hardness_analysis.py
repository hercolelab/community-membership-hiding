def load_outcomes(dataset: str, alg: str) -> pd.DataFrame:
    """
    Load per-target-node success outcomes (``goal``) for every method, pooled across
    seeds and budget factors.

    Returns a long DataFrame: [target_node, method, seed, beta, goal].
    """
    rows = []
    for method, stem in METHOD_FILE.items():
        for seed in SEEDS:
            for beta in BETAS:
                path = os.path.join(
                    RUNS_DIR, f"seed_{seed}", dataset, alg, f"tau_{TAU}",
                    f"betaFactor_{beta}", "json_results", f"{stem}.json",
                )
                if not os.path.exists(path):
                    continue
                with open(path, "r") as f:
                    log = json.load(f)
                for node, goal in zip(log["target_node"], log["goal"]):
                    rows.append((int(node), method, seed, beta, int(goal)))
    return pd.DataFrame(rows, columns=["target_node", "method", "seed", "beta", "goal"])


def build_master_table(datasets: List[str], algs: List[str]) -> pd.DataFrame:
    """
    Assemble the full tidy table joining outcomes with node features for every
    (dataset, detection algorithm). One row per (dataset, alg, method, seed, beta,
    target_node).
    """
    frames = []
    for dataset in datasets:
        graph = import_graph(dataset)
        for alg in algs:
            try:
                communities = get_partition(dataset, alg, graph)
            except Exception as exc:  # pragma: no cover - environment dependent
                print(f"  [skip] could not get partition {dataset}/{alg}: {exc}")
                continue
            feat = build_node_feature_table(dataset, alg, graph, communities)
            outcomes = load_outcomes(dataset, alg)
            if outcomes.empty:
                print(f"  [skip] no outcomes for {dataset}/{alg}")
                continue
            merged = outcomes.join(feat, on="target_node")
            merged.insert(0, "detection_alg", alg)
            merged.insert(0, "dataset", dataset)
            frames.append(merged)
            print(f"  [table] {dataset}/{alg}: {len(merged)} rows")
    if not frames:
        raise RuntimeError("No data assembled - check that runs/partitions exist.")
    master = pd.concat(frames, ignore_index=True)
    master["method_name"] = master["method"].map(METHOD_RENAME)
    check_dir(OUT_DIR)
    master.to_csv(os.path.join(OUT_DIR, "master_table.csv"), index=False)
    return master


